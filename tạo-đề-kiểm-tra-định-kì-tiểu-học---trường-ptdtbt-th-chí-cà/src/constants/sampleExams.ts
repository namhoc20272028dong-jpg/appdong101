// Helper to make exam
function createSampleExam(
  id: string,
  subject: any,
  grade: any,
  semester: any,
  title: string,
  questions: any[],
  passage?: any
): ExamPaper {
  const config = getDefaultConfig(subject, grade, semester);
  const matrix = generateMatrixFromQuestions(questions);
  const specifications = generateSpecsFromQuestions(questions);

  return {
    id,
    title,
    header: {
      governingBody: 'UBND XÃ XÍN MẦN',
      schoolName: 'TRƯỜNG PTDTBT TH CHÍ CÀ',
      examTitle: 'ĐỀ KIỂM TRA ĐỊNH KÌ',
      examPeriod: semester,
      schoolYear: '2026–2027',
      subject,
      grade,
      durationMinutes: subject === 'Toán' ? 40 : 50,
      examCode: '101',
    },
    config,
    readingPassage: passage,
    questions,
    matrix,
    specifications,
    createdAt: '2026-10-29T08:00:00Z',
    updatedAt: '2026-10-29T08:00:00Z',
    status: 'approved',
    tags: ['Minh họa GDPT 2018', 'Đã thẩm định', 'Trường PTDTBT TH Chí Cà'],
  };
}

